//! A small single-stroke font for silkscreen (Gerber has no text: letters
//! are drawn as lines). Capitals, digits and a few marks on a 4 × 6 grid.

use crate::geom::P;

fn glyph(c: char) -> &'static str {
    match c.to_ascii_uppercase() {
        '0' => "1,0 3,0 4,1 4,5 3,6 1,6 0,5 0,1 1,0;1,1 3,5",
        '1' => "1,5 2,6 2,0;1,0 3,0",
        '2' => "0,5 1,6 3,6 4,5 4,4 0,0 4,0",
        '3' => "0,5 1,6 3,6 4,5 4,4 3,3 4,2 4,1 3,0 1,0 0,1;1,3 3,3",
        '4' => "3,0 3,6 0,2 4,2",
        '5' => "4,6 0,6 0,3 3,3 4,2 4,1 3,0 0,0",
        '6' => "3,6 1,6 0,5 0,1 1,0 3,0 4,1 4,2 3,3 0,3",
        '7' => "0,6 4,6 1,0",
        '8' => "1,3 0,4 0,5 1,6 3,6 4,5 4,4 3,3 1,3 0,2 0,1 1,0 3,0 4,1 4,2 3,3",
        '9' => "4,3 1,3 0,4 0,5 1,6 3,6 4,5 4,1 3,0 1,0",
        'A' => "0,0 0,4 2,6 4,4 4,0;0,3 4,3",
        'B' => "0,0 0,6 3,6 4,5 4,4 3,3 0,3;3,3 4,2 4,1 3,0 0,0",
        'C' => "4,5 3,6 1,6 0,5 0,1 1,0 3,0 4,1",
        'D' => "0,0 0,6 2,6 4,4 4,2 2,0 0,0",
        'E' => "4,6 0,6 0,0 4,0;0,3 3,3",
        'F' => "4,6 0,6 0,0;0,3 3,3",
        'G' => "4,5 3,6 1,6 0,5 0,1 1,0 3,0 4,1 4,3 2,3",
        'H' => "0,0 0,6;4,0 4,6;0,3 4,3",
        'I' => "1,6 3,6;2,6 2,0;1,0 3,0",
        'J' => "4,6 4,1 3,0 1,0 0,1",
        'K' => "0,0 0,6;4,6 0,2;1,3 4,0",
        'L' => "0,6 0,0 4,0",
        'M' => "0,0 0,6 2,3 4,6 4,0",
        'N' => "0,0 0,6 4,0 4,6",
        'O' => "1,0 3,0 4,1 4,5 3,6 1,6 0,5 0,1 1,0",
        'P' => "0,0 0,6 3,6 4,5 4,4 3,3 0,3",
        'Q' => "1,0 3,0 4,1 4,5 3,6 1,6 0,5 0,1 1,0;2,2 4,0",
        'R' => "0,0 0,6 3,6 4,5 4,4 3,3 0,3;2,3 4,0",
        'S' => "4,5 3,6 1,6 0,5 0,4 1,3 3,3 4,2 4,1 3,0 1,0 0,1",
        'T' => "0,6 4,6;2,6 2,0",
        'U' => "0,6 0,1 1,0 3,0 4,1 4,6",
        'V' => "0,6 2,0 4,6",
        'W' => "0,6 1,0 2,3 3,0 4,6",
        'X' => "0,0 4,6;0,6 4,0",
        'Y' => "0,6 2,3 4,6;2,3 2,0",
        'Z' => "0,6 4,6 0,0 4,0",
        '+' => "0,3 4,3;2,1 2,5",
        '-' => "0,3 4,3",
        '.' => "2,0 2,0.5",
        ',' => "2,0.5 1.5,-0.5",
        '/' => "0,0 4,6",
        '_' => "0,0 4,0",
        '(' => "3,6 2,4.5 2,1.5 3,0",
        ')' => "1,6 2,4.5 2,1.5 1,0",
        ':' => "2,1 2,1.5;2,4 2,4.5",
        '=' => "0,2 4,2;0,4 4,4",
        '#' => "1,0 1,6;3,0 3,6;0,2 4,2;0,4 4,4",
        _ => "",
    }
}

/// Strokes for `text` of capital height `h` mm, centred on `at`, as polylines;
/// `mirror` reads correctly from the bottom of the board.
pub fn strokes(text: &str, at: P, h: f64, mirror: bool) -> Vec<Vec<P>> {
    let s = h / 6.0;
    let advance = 6.0;
    let n = text.chars().count() as f64;
    let width = (n * advance - 2.0) * s;
    let mut out = Vec::new();
    for (i, c) in text.chars().enumerate() {
        let x0 = i as f64 * advance;
        for stroke in glyph(c).split(';').filter(|t| !t.is_empty()) {
            let pts: Vec<P> = stroke
                .split(' ')
                .filter_map(|p| {
                    let (x, y) = p.split_once(',')?;
                    let (x, y) = (x.parse::<f64>().ok()?, y.parse::<f64>().ok()?);
                    let mut px = (x0 + x) * s - width / 2.0;
                    if mirror {
                        px = -px;
                    }
                    Some([at[0] + px, at[1] + y * s - h / 2.0])
                })
                .collect();
            if pts.len() >= 2 {
                out.push(pts);
            }
        }
    }
    out
}

/// Width of `text` at height `h` (mm).
pub fn width(text: &str, h: f64) -> f64 {
    let n = text.chars().count() as f64;
    ((n * 6.0 - 2.0) * h / 6.0).max(0.0)
}
